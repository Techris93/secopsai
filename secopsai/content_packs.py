    summary = case_data.get("summary") or ""
    iocs = case_data.get("iocs") or []
    diff_summary = case_data.get("diff_summary") or "Obfuscated lifecycle execution detected in package manifest."

    pkg_tag = f"{package}@{version}" if version else package

