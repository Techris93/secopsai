ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CONTENT_PACKS_DIR = ROOT / "reports" / "content_packs"


def _now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def content_packs_dir(custom_path: Optional[str] = None) -> Path:
    target = Path(custom_path).expanduser().resolve() if custom_path else DEFAULT_CONTENT_PACKS_DIR
    target.mkdir(parents=True, exist_ok=True)
    return target


def _clean_text(text: Any, limit: int = 5000) -> str:
    return str(text or "").strip()[:limit]


