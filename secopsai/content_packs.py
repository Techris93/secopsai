    tweet3 = f"[3/5] Differential & Heuristic Findings:\n\n- Differential Delta: {diff_summary[:200]}\n\nCheck attached code diff asset (01_ast_diff.txt) for exact injection points."
    
    ioc_lines = "\n".join([f"- `{ioc}`" for ioc in iocs[:4]]) if iocs else f"- Package: `{pkg_tag}`\n- Ecosystem: `{ecosystem}`\n- Status: Confirmed Malicious"
