def generate_content_pack(
    case_id: str,
    *,
    db_path: Optional[str] = None,
    output_dir: Optional[str] = None,
) -> Dict[str, Any]:
    """Generate a full social media & community content pack for a research case or finding."""
    soc_store.init_db(db_path)
    clean_id = _clean_text(case_id, 80).upper()

    case_data: Dict[str, Any] = {
        "case_id": clean_id,
        "title": f"Security Research Analysis: {clean_id}",
        "package": clean_id,
        "version": "latest",
        "ecosystem": "npm",
        "severity": "high",
        "summary": "Automated AST differential analysis identified suspicious behaviors in package release.",
        "evidence": [],
        "iocs": [],
        "diff_summary": "Ast-aware static heuristics flagged unexpected payload.",
        "baseline_version": "previous release",
    }

    with soc_store.connect(db_path) as conn:
        row = conn.execute("SELECT * FROM research_cases WHERE case_id = ?", (clean_id,)).fetchone()
        if row:
            case_row = dict(row)
            case_data["title"] = str(case_row.get("title") or case_data["title"])
            case_data["summary"] = str(case_row.get("summary") or case_data["summary"])
            case_data["severity"] = str(case_row.get("severity") or case_data["severity"])

            subject = conn.execute("SELECT * FROM research_subjects WHERE case_id = ? LIMIT 1", (clean_id,)).fetchone()
            if subject:
                subj_dict = dict(subject)
                case_data["package"] = str(subj_dict.get("name") or case_data["package"])
                case_data["ecosystem"] = str(subj_dict.get("ecosystem") or case_data["ecosystem"])
                case_data["version"] = str(subj_dict.get("version") or case_data["version"])

            for ioc_row in conn.execute("SELECT value FROM research_iocs WHERE case_id = ?", (clean_id,)).fetchall():
                case_data["iocs"].append(str(ioc_row["value"]))

            for evd_row in conn.execute("SELECT title, sha256 FROM research_evidence WHERE case_id = ? LIMIT 5", (clean_id,)).fetchall():
                title = str(evd_row["title"] or "")
                sha = str(evd_row["sha256"] or "")
                if title:
                    case_data["evidence"].append(f"{title} (SHA: {sha[:16]}...)" if sha else title)
        else:
            f_row = conn.execute("SELECT * FROM findings WHERE finding_id = ?", (clean_id,)).fetchone()
            if f_row:
                f_dict = dict(f_row)
                case_data["title"] = str(f_dict.get("title") or case_data["title"])
                case_data["summary"] = str(f_dict.get("summary") or case_data["summary"])
                case_data["package"] = str(f_dict.get("package") or case_data["package"])
                case_data["ecosystem"] = str(f_dict.get("ecosystem") or case_data["ecosystem"])
                case_data["version"] = str(f_dict.get("new_version") or f_dict.get("version") or "")
                case_data["baseline_version"] = str(f_dict.get("old_version") or "")
                case_data["severity"] = str(f_dict.get("severity") or case_data["severity"])

    pack_id = f"CPK-{clean_id}"
    base_dir = content_packs_dir(output_dir) / pack_id
    base_dir.mkdir(parents=True, exist_ok=True)
    assets_dir = base_dir / "assets"
    assets_dir.mkdir(parents=True, exist_ok=True)

    twitter_content = _format_twitter_thread(case_data)
    reddit_content = _format_reddit_post(case_data)
    linkedin_content = _format_linkedin_post(case_data)

    (base_dir / "twitter_thread.md").write_text(twitter_content, encoding="utf-8")
    (base_dir / "reddit_post.md").write_text(reddit_content, encoding="utf-8")
    (base_dir / "linkedin_post.md").write_text(linkedin_content, encoding="utf-8")

    evd_txt = "\n".join([f"[!] HIT: {item}" for item in case_data["evidence"]]) if case_data["evidence"] else "[!] Flagged: Obfuscated eval and outbound network communication"
    diff_asset = f"""================================================================================
SECOPSAI AST DIFFERENTIAL SNAPSHOT
Target: {case_data["package"]}@{case_data["version"]} ({case_data["ecosystem"]})
Comparison: Baseline ({case_data.get("baseline_version")}) -> Target ({case_data.get("version")})
================================================================================
{evd_txt}
================================================================================
"""
    (assets_dir / "01_ast_diff.txt").write_text(diff_asset, encoding="utf-8")

    attack_flow = f"""[1. Ingestion] -> [{case_data["ecosystem"]} Registry Feed]
[2. AST Parser] -> [Identified anomalous execution sink]
[3. Diff Engine] -> [0 benign delta, high-entropy payload]
[4. Verdict] -> [MALICIOUS ISOLATION]
"""
    (assets_dir / "02_attack_flow.txt").write_text(attack_flow, encoding="utf-8")
    (assets_dir / "03_iocs.json").write_text(json.dumps(case_data["iocs"], indent=2), encoding="utf-8")

    manifest = {
        "pack_id": pack_id,
        "case_id": clean_id,
        "created_at": _now(),
        "package": case_data["package"],
        "ecosystem": case_data["ecosystem"],
        "version": case_data["version"],
        "severity": case_data["severity"],
        "content": {
            "twitter_thread": twitter_content,
            "reddit_post": reddit_content,
            "linkedin_post": linkedin_content,
        },
        "files": {
            "twitter_thread": str(base_dir / "twitter_thread.md"),
            "reddit_post": str(base_dir / "reddit_post.md"),
            "linkedin_post": str(base_dir / "linkedin_post.md"),
            "assets": [str(p) for p in assets_dir.glob("*")],
        },
    }
    (base_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def list_content_packs(*, output_dir: Optional[str] = None) -> List[Dict[str, Any]]:
    """List all available content packs."""
    base = content_packs_dir(output_dir)
    packs: List[Dict[str, Any]] = []
    for path in sorted(base.glob("CPK-*"), reverse=True):
        if not path.is_dir():
            continue
        manifest_file = path / "manifest.json"
        if manifest_file.exists():
            try:
                pack_data = json.loads(manifest_file.read_text(encoding="utf-8"))
                if "content" not in pack_data:
                    pack_data["content"] = {}
                    for key, fname in [("twitter_thread", "twitter_thread.md"), ("reddit_post", "reddit_post.md"), ("linkedin_post", "linkedin_post.md")]:
                        fpath = path / fname
                        if fpath.exists():
                            pack_data["content"][key] = fpath.read_text(encoding="utf-8")
                packs.append(pack_data)
            except Exception:
                continue
    return packs
